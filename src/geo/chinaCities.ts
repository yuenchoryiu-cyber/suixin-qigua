export type CityEntry = {
  name: string
  lat: number
  lon: number
}

export type ProvinceEntry = {
  name: string
  cities: CityEntry[]
}

type Row = [string, number, number]

function mapCities(rows: Row[]): CityEntry[] {
  return rows.map(([name, lat, lon]) => ({ name, lat, lon }))
}

function P(name: string, rows: Row[]): ProvinceEntry {
  return { name, cities: mapCities(rows) }
}

